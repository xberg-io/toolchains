BETA = '["b:one"]\nrun = "echo b"\n'
SHARED_TOML = "mise-tasks/shared.toml"
ALPHA_FILE = "mise-tasks/.shared/alpha/two.sh"
MANIFEST = "mise-tasks/.shared/.manifest"


class TaskSetTestCase(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        self.baseline = self.root / "baseline.toml"
        self.baseline.write_text(BASELINE)
        self.sets = self.root / "task-sets"
        (self.sets / "alpha").mkdir(parents=True)
        (self.sets / "alpha.toml").write_text(ALPHA)
        (self.sets / "alpha" / "two.sh").write_text("#!/bin/sh\necho two\n")
        (self.sets / "beta.toml").write_text(BETA)
        self.repo = self.root / "repo"
        self.repo.mkdir()
        self.write("mise.toml", MISE)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def write(self, name: str, content: str) -> None:
        path = self.repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)

    def read(self, name: str) -> str:
        return (self.repo / name).read_text()

    def select(self, *sets: str, extra: str = "") -> None:
        names = ", ".join(f'"{name}"' for name in sets)
        self.write("toolchains.toml", f'baseline = "v1.6.0"\ntask_sets = [{names}]\n{extra}')

    def main(self, command: str, *extra: str) -> tuple[int, str, str]:
        out, err = io.StringIO(), io.StringIO()
        args = [command, "--baseline", str(self.baseline), "--repo", str(self.repo), "--sets-dir", str(self.sets)]
        with redirect_stdout(out), redirect_stderr(err):
            code = toolchains.main([*args, *extra])
        return code, out.getvalue(), err.getvalue()

    def synced(self, *extra: str) -> str:
        code, out, err = self.main("sync", *extra)
        self.assertEqual((code, err), (0, ""))
        return out

    def assert_check(self, expected_code: int, *messages: str) -> None:
        code, _, err = self.main("check")
        self.assertEqual(code, expected_code, err)
        for message in messages:
            self.assertIn(message, err)


class SyncTaskSetsTest(TaskSetTestCase):
    def test_writes_shared_tasks_files_manifest_and_includes(self) -> None:
        self.select("alpha", "beta")

        out = self.synced()

        self.assertIn("updated 3 shared task files", out)
        shared = self.read(SHARED_TOML)
        self.assertTrue(
            shared.startswith("# Generated by scripts/toolchains.py sync from xberg-io/toolchains v1.6.0.\n")
        )
        self.assertIn("# Task sets: alpha, beta\n", shared)
        self.assertIn('# The second task.\n["a:two"]', shared)
        self.assertEqual(sorted(tomllib.loads(shared)), ["a:one", "a:two", "b:one"])
        self.assertEqual(self.read(ALPHA_FILE), "#!/bin/sh\necho two\n")
        self.assertEqual((self.repo / ALPHA_FILE).stat().st_mode & 0o777, 0o755)
        self.assertEqual(self.read(MANIFEST).splitlines()[1:], [ALPHA_FILE, SHARED_TOML])
        self.assertEqual(
            self.read("mise.toml"), MISE + '\n[task_config]\nincludes = ["mise-tasks", "mise-tasks/shared.toml"]\n'
        )
        self.assert_check(0)

    def test_second_sync_changes_nothing(self) -> None:
        self.select("alpha")
        self.synced()
        before = {path: path.read_bytes() for path in self.repo.rglob("*") if path.is_file()}

        out = self.synced()

        self.assertNotIn("shared task files", out)
        self.assertEqual({path: path.read_bytes() for path in self.repo.rglob("*") if path.is_file()}, before)

    def test_adds_only_the_missing_entry_to_existing_includes(self) -> None:
        cases = {
            '[task_config]\nincludes = [\n  "mise-tasks",\n  "mise-tasks/rust.toml",\n]\n': (
                '[task_config]\nincludes = [\n  "mise-tasks/shared.toml",\n  "mise-tasks",\n  "mise-tasks/rust.toml",\n]\n'
            ),
            '[task_config] # tasks\nincludes = ["mise-tasks"]\n': (
                '[task_config] # tasks\nincludes = ["mise-tasks/shared.toml", "mise-tasks"]\n'
            ),
            "[task_config]\nincludes = []\n": '[task_config]\nincludes = ["mise-tasks", "mise-tasks/shared.toml"]\n',
            '[task_config]\ndir = "."\n': '[task_config]\nincludes = ["mise-tasks", "mise-tasks/shared.toml"]\ndir = "."\n',
        }
        self.select("beta")
        for task_config, expected in cases.items():
            with self.subTest(task_config=task_config):
                self.write("mise.toml", f"{task_config}\n{MISE}")

                self.synced()

                self.assertEqual(self.read("mise.toml"), f"{expected}\n{MISE}")

    def test_keeps_default_task_directories_the_repository_uses(self) -> None:
        (self.repo / ".mise" / "tasks").mkdir(parents=True)
        self.select("beta")
        for task_config in ("", '[task_config]\ndir = "."\n\n'):
            with self.subTest(task_config=task_config):
                self.write("mise.toml", task_config + MISE)

                self.synced()

                expected = 'includes = ["mise-tasks", ".mise/tasks", "mise-tasks/shared.toml"]'
                self.assertIn(expected, self.read("mise.toml"))

    def test_deselected_set_files_are_deleted_with_their_directories(self) -> None:
        self.select("alpha", "beta")
        self.synced()
        self.select("beta")

        out = self.synced()

        self.assertIn(f"{ALPHA_FILE} (deleted)", out)
        self.assertFalse((self.repo / "mise-tasks" / ".shared" / "alpha").exists())
        self.assertEqual(sorted(tomllib.loads(self.read(SHARED_TOML))), ["b:one"])
        self.assert_check(0)

    def test_no_sets_left_removes_every_generated_file(self) -> None:
        self.select("alpha")
        self.synced()
        self.write("toolchains.toml", 'baseline = "v1.6.0"\n')

        self.synced()

        self.assertEqual(sorted(p.name for p in (self.repo / "mise-tasks").iterdir()), [])
        self.assert_check(0)

    def test_files_sync_did_not_write_are_left_alone(self) -> None:
        self.select("alpha")
        self.synced()
        self.write("mise-tasks/.shared/alpha/notes.txt", "mine")

        self.synced()

        self.assertEqual(self.read("mise-tasks/.shared/alpha/notes.txt"), "mine")
        self.assert_check(1, "mise-tasks/.shared/alpha/notes.txt: not written by sync")

    def test_ref_names_the_tag_in_the_header(self) -> None:
        self.select("beta")

        self.synced("--ref", "v2.0.0")

        self.assertIn("xberg-io/toolchains v2.0.0.", self.read(SHARED_TOML))
        self.assertTrue(self.read("toolchains.toml").startswith('baseline = "v2.0.0"\n'))
        self.assert_check(0)

    def test_unknown_set_fails_and_writes_nothing(self) -> None:
        self.select("alpha", "gamma")

        code, _, err = self.main("sync")

        self.assertEqual(code, 2)
        self.assertIn("no such task set", err)
        self.assertIn("gamma", err)
        self.assertEqual(self.read("mise.toml"), MISE)
        self.assertFalse((self.repo / "mise-tasks").exists())

    def test_override_omits_the_task_and_its_alias(self) -> None:
        self.select("alpha", extra='[task_overrides]\n"a:two" = "runs the repository build first"\n')
        self.write("mise-tasks/local.toml", '["a:two"]\nrun = "echo mine"\n')

        self.synced()

        shared = self.read(SHARED_TOML)
        self.assertEqual(sorted(tomllib.loads(shared)), ["a:one"])
        self.assertIn("# Omitted by task_overrides: a:two\n", shared)
        self.assertNotIn("# The second task.", shared)
        self.assert_check(0)

    def test_two_sets_defining_one_task_is_an_error(self) -> None:
        (self.sets / "gamma.toml").write_text('["b:one"]\nrun = "echo again"\n')
        self.select("beta", "gamma")

        code, _, err = self.main("sync")

        self.assertEqual(code, 2)
        self.assertIn("task sets beta and gamma both define b:one", err)


class CheckTaskSetsTest(TaskSetTestCase):
    def setUp(self) -> None:
        super().setUp()
        self.select("alpha", "beta")
        self.synced()
        self.assert_check(0)

    def test_edited_shared_toml_is_drift(self) -> None:
        self.write(SHARED_TOML, self.read(SHARED_TOML).replace("echo one", "echo edited"))

        self.assert_check(1, f"drift: {SHARED_TOML}: differs from the task sets; run sync")

    def test_edited_or_missing_set_file_is_drift(self) -> None:
        self.write(ALPHA_FILE, "#!/bin/sh\necho edited\n")
        self.assert_check(1, f"drift: {ALPHA_FILE}: differs from the task sets")

        (self.repo / ALPHA_FILE).unlink()
        self.assert_check(1, f"drift: {ALPHA_FILE}: missing; run sync")

    @unittest.skipIf(os.name == "nt", "no executable bit on Windows")
    def test_non_executable_set_file_is_drift(self) -> None:
        (self.repo / ALPHA_FILE).chmod(0o644)

        self.assert_check(1, f"drift: {ALPHA_FILE}: not executable")

    def test_set_change_upstream_is_drift(self) -> None:
        (self.sets / "beta.toml").write_text('["b:one"]\nrun = "echo b2"\n')

        self.assert_check(1, f"drift: {SHARED_TOML}: differs from the task sets")

    def test_missing_include_is_drift(self) -> None:
        self.write("mise.toml", MISE + '\n[task_config]\nincludes = ["mise-tasks"]\n')

        self.assert_check(1, 'mise.toml: [task_config] includes lacks "mise-tasks/shared.toml"')

    def test_unknown_set_is_drift(self) -> None:
        self.select("alpha", "beta", "gamma")

        self.assert_check(1, "task set 'gamma': no such set")

    def test_stale_generated_files_without_sets_are_drift(self) -> None:
        self.write("toolchains.toml", 'baseline = "v1.6.0"\n')

        self.assert_check(1, f"drift: {SHARED_TOML}: not written by sync", f"drift: {ALPHA_FILE}: not written by sync")

    def test_local_duplicates_are_drift_wherever_they_are_defined(self) -> None:
        cases = {
            "mise.toml": (MISE + '\n[tasks."a:one"]\nrun = "x"\n', "a:one: mise.toml defines a task"),
            "mise-tasks/extra.toml": ('["b:one"]\nrun = "x"\n', "b:one: mise-tasks/extra.toml defines a task"),
            "mise-tasks/a/one.sh": ("#!/bin/sh\n", "a:one: mise-tasks/a/one.sh defines a task"),
            "mise-tasks/local.toml": ('["mine"]\nalias = "a:2"\nrun = "x"\n', "a:2: mise-tasks/local.toml defines"),
        }
        original = self.read("mise.toml")
        for name, (content, message) in cases.items():
            with self.subTest(name=name):
                self.write(name, content)
                (self.repo / name).chmod(0o755)

                self.assert_check(1, message)

                if name == "mise.toml":
                    self.write(name, original)
                else:
                    (self.repo / name).unlink()
        self.assert_check(0)

    def test_alias_collision_names_the_task_to_override(self) -> None:
        self.write("mise-tasks/local.toml", '["a:2"]\nrun = "x"\n')

        self.assert_check(1, "a:2: mise-tasks/local.toml defines a task task set alpha provides (alias of a:two)")

    def test_non_executable_or_hidden_files_are_not_tasks(self) -> None:
        self.write("mise-tasks/a/one.sh", "#!/bin/sh\n")
        (self.repo / "mise-tasks" / "a" / "one.sh").chmod(0o644)

        self.assert_check(0)

    def test_override_problems_are_drift(self) -> None:
        cases = {
            '"a:one" = ""': "a:one: task_overrides entry has no reason",
            '"c:one" = "x"': "c:one: task_overrides entry for a task no selected set provides",
            '"a:2" = "x"': "a:2: task_overrides names an alias; override 'a:two' instead",
        }
        for entry, message in cases.items():
            with self.subTest(entry=entry):
                self.select("alpha", "beta", extra=f"[task_overrides]\n{entry}\n")
                self.synced()

                self.assert_check(1, message)

    def test_overridden_local_task_passes(self) -> None:
        self.select("alpha", "beta", extra='[task_overrides]\n"a:one" = "needs the repository build"\n')
        self.write("mise-tasks/local.toml", '["a:one"]\nrun = "x"\n')
        self.synced()

        self.assert_check(0)


class RealTaskSetsTest(unittest.TestCase):
    sets_dir = ROOT / "task-sets"
    names = tuple(sorted(path.stem for path in (ROOT / "task-sets").glob("*.toml")))

    def test_every_set_loads_and_no_two_define_one_task(self) -> None:
        sets, unknown = toolchains.resolve_sets(self.sets_dir, self.names)

        self.assertEqual(unknown, [])
        self.assertEqual(
            self.names,
            (
                "alef",
                "alef-version",
                "deps-refresh",
                "docs-site",
                "docs-snippets",
                "governance",
                "lint-format",
                "plugin",
                "rust",
            ),
        )
        self.assertTrue(all(task_set.tasks for task_set in sets))

    def test_rendering_keeps_every_task_and_overrides_drop_exactly_one(self) -> None:
        for task_set in toolchains.resolve_sets(self.sets_dir, self.names)[0]:
            with self.subTest(set=task_set.name):
                rendered = tomllib.loads(toolchains.render_shared([task_set], {}, "v0"))
                self.assertEqual(rendered, task_set.tasks)
                for task in task_set.tasks:
                    dropped = tomllib.loads(toolchains.render_shared([task_set], {task: "x"}, "v0"))
                    self.assertEqual(sorted(dropped), sorted(set(task_set.tasks) - {task}))

    def test_no_set_task_hard_codes_a_repository_name(self) -> None:
        text = "\n".join(path.read_text() for path in self.sets_dir.glob("*.toml"))

        for repository in ("xberg", "crawlberg", "liter-llm", "html-to-markdown", "tree-sitter", "sceptre"):
            match = re.search(rf"(?<![\w-]){re.escape(repository)}(?![\w-])", text)
            self.assertIsNone(match, f"a task set names the repository {repository}")

    def test_set_file_tasks_match_the_deprecated_remote_tasks(self) -> None:
        pairs = {
            "governance/hooks-install.sh": "governance/hooks-install.sh",
            "alef/pin-check.sh": "alef/pin-check.sh",
            "alef/regenerate.sh": "alef/regenerate.sh",
            "alef/verify-strict.sh": "alef/verify-strict.sh",
            "alef-version/show.sh": "version/cargo.sh",
            "deps-refresh/refresh.sh": "deps/refresh.sh",
        }
        shipped = sorted(p.relative_to(self.sets_dir).as_posix() for p in self.sets_dir.rglob("*.sh"))

        self.assertEqual(shipped, sorted(pairs))
        for in_set, remote in pairs.items():
            with self.subTest(file=in_set):
                self.assertEqual((self.sets_dir / in_set).read_bytes(), (ROOT / "tasks" / remote).read_bytes())
                self.assertTrue(os.access(self.sets_dir / in_set, os.X_OK))


def required_tasks(path: Path) -> list[str]:
    """Repository-owned tasks a set calls, from its `# requires: <task> (...)` header lines."""
    return re.findall(r"^# requires: (\S+)", path.read_text(), re.MULTILINE)


@unittest.skipUnless(shutil.which("mise"), "mise is not on PATH")
class MiseValidatesTaskSetsTest(unittest.TestCase):
    """Each set, synced alone into a scratch repository, passes `mise tasks validate` and runs."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name).resolve()
        (self.root / "empty.toml").write_text("")
        self.bin = self.root / "bin"
        self.bin.mkdir()
        self.calls = self.root / "calls"

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def scratch_repo(self, name: str, *task_sets: str) -> Path:
        repo = self.root / name
        repo.mkdir()
        local = "".join(
            f'\n[tasks."{task}"]\nrun = "true"\n' for task in required_tasks(ROOT / "task-sets" / f"{name}.toml")
        )
        # No [tools]: mise would install them before running a task. ~keep
        (repo / "mise.toml").write_text(local)
        (repo / "toolchains.toml").write_text(f"task_sets = {list(task_sets)!r}\n".replace("'", '"'))
        baseline = repo / "baseline.toml"
        baseline.write_text(BASELINE)
        with redirect_stdout(io.StringIO()):
            self.assertEqual(toolchains.main(["sync", "--baseline", str(baseline), "--repo", str(repo)]), 0)
        baseline.unlink()
        return repo

    def mise(self, repo: Path, *args: str, **env: str) -> subprocess.CompletedProcess[str]:
        full_env = {
            **os.environ,
            "PATH": f"{self.bin}{os.pathsep}{os.environ['PATH']}",
            "MISE_CEILING_PATHS": str(self.root),
            "MISE_TRUSTED_CONFIG_PATHS": str(repo),
            "MISE_GLOBAL_CONFIG_FILE": str(self.root / "empty.toml"),
            "MISE_SYSTEM_CONFIG_FILE": str(self.root / "empty.toml"),
            **env,
        }
        return subprocess.run(["mise", *args], cwd=repo, env=full_env, capture_output=True, text=True, check=False)

    def stub(self, name: str) -> None:
        path = self.bin / name
        path.write_text(f'#!/bin/sh\necho "{name} $*" >> "{self.calls}"\n')
        path.chmod(0o755)

    def test_every_set_validates(self) -> None:
        names = sorted(path.stem for path in (ROOT / "task-sets").glob("*.toml"))
        self.assertEqual(len(names), 9)
        for name in names:
            with self.subTest(set=name):
                repo = self.scratch_repo(name, name)

                result = self.mise(repo, "tasks", "validate")

                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                tasks = toolchains.load_toml(ROOT / "task-sets" / f"{name}.toml")
                self.assertIn(
                    f"All {len(tasks) + len(required_tasks(ROOT / 'task-sets' / f'{name}.toml'))} task(s)",
                    result.stdout + result.stderr,
                )

    def test_validate_catches_a_missing_required_task(self) -> None:
        repo = self.scratch_repo("alef-version", "alef-version")
        (repo / "mise.toml").write_text('[task_config]\nincludes = ["mise-tasks", "mise-tasks/shared.toml"]\n')

        result = self.mise(repo, "tasks", "validate")

        self.assertNotEqual(result.returncode, 0)
        self.assertIn("version:sync", result.stdout + result.stderr)

    def test_poly_and_docs_tasks_run_with_their_alias_and_env(self) -> None:
        self.stub("poly")
        self.stub("pnpm")
        repo = self.scratch_repo("lint-format", "lint-format", "docs-site")

        for args, env in (
            (["run", "lint:check"], {}),
            (["run", "format:check"], {}),
            (["run", "docs:lint:prose"], {"DOCS_DIR": "site"}),
        ):
            result = self.mise(repo, *args, **env)
            self.assertEqual(result.returncode, 0, result.stderr)

        self.assertEqual(
            self.calls.read_text().splitlines(),
            ["poly lint .", "poly fmt --check .", "pnpm exec textlint site/src/content/docs/**/*.{md,mdx}"],
        )

    def test_shared_file_task_runs_with_usage_args(self) -> None:
        self.stub("cargo")
        repo = self.scratch_repo("deps-refresh", "deps-refresh")

        result = self.mise(repo, "run", "deps", "update", "rust")

        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.calls.read_text().splitlines(), ["cargo update"])


